package domain

import (
	"errors"
	"math/big"
)

const OrcaMinTick int32 = -443636
const OrcaMaxTick int32 = 443636

func OrcaSqrtPriceAtTick(tick int32) (*big.Int, error) {
	if tick < OrcaMinTick || tick > OrcaMaxTick {
		return nil, errors.New("ORCA_TICK_RANGE")
	}
	pos := []string{"79232123823359799118286999567", "79236085330515764027303304731", "79244008939048815603706035061", "79259858533276714757314932305", "79291567232598584799939703904", "79355022692464371645785046466", "79482085999252804386437311141", "79736823300114093921829183326", "80248749790819932309965073892", "81282483887344747381513967011", "83390072131320151908154831281", "87770609709833776024991924138", "97234110755111693312479820773", "119332217159966728226237229890", "179736315981702064433883588727", "407748233172238350107850275304", "2098478828474011932436660412517", "55581415166113811149459800483533", "38992368544603139932233054999993551"}
	neg := []string{"18445821805675392311", "18444899583751176498", "18443055278223354162", "18439367220385604838", "18431993317065449817", "18417254355718160513", "18387811781193591352", "18329067761203520168", "18212142134806087854", "17980523815641551639", "17526086738831147013", "16651378430235024244", "15030750278693429944", "12247334978882834399", "8131365268884726200", "3584323654723342297", "696457651847595233", "26294789957452057", "37481735321082"}
	factors := pos
	shift := uint(96)
	abs := tick
	if tick < 0 {
		abs = -tick
		factors = neg
		shift = 64
	}
	ratio := new(big.Int).Lsh(big.NewInt(1), shift)
	for i, n := range factors {
		if abs&(1<<i) != 0 {
			f, _ := new(big.Int).SetString(n, 10)
			ratio.Rsh(new(big.Int).Mul(ratio, f), shift)
		}
	}
	if tick >= 0 {
		ratio.Rsh(ratio, 32)
	}
	return ratio, nil
}
