#!/usr/bin/env python3
"""Project authenticated compiler runtime metadata into independent Go admission data.

Reference-only runtimes over EIP170 never become an admitted service template.
"""
from pathlib import Path
import hashlib,json,subprocess,secrets
ROOT=Path(__file__).resolve().parents[3]
REF=ROOT/'integration/tools/reference/balancer-managed-fees'
def require(value,message):
 if not value:raise ValueError(message)
def atomic(path,data):
 temporary=path.with_name(path.name+'.'+secrets.token_hex(6)+'.tmp')
 try:temporary.write_text(data);temporary.replace(path)
 finally:temporary.unlink(missing_ok=True)
def generate():
 meta=json.loads((REF/'runtime-metadata.json').read_text())
 require(meta['revision']=='e281ff40583c39bf1d46c322334b2b13936e0e33','source revision changed')
 require(meta.get('eip170_deployable') is True and 0<meta['runtime_bytes']<=24576,'reference-only or oversized runtime cannot become a service template')
 raw=bytes.fromhex(meta['deployedBytecode'].removeprefix('0x'));require(len(raw)==meta['runtime_bytes'],'runtime length differs')
 normalized=bytearray(raw);refs=[];end=0
 for ast,spans in meta['immutableReferences'].items():
  declaration=meta['immutable_ast'][ast]
  for span in spans:refs.append({'start':span['start'],'length':span['length'],'name':declaration['name'],'source':declaration['source']})
 for span in sorted(refs,key=lambda row:row['start']):
  start,length=span['start'],span['length'];require(length==32 and start>=end and start+length<=len(raw),'bad immutable span')
  normalized[start:start+length]=bytes(length);end=start+length
 require(hashlib.sha256(normalized).hexdigest()==meta['normalized_runtime_sha256'],'normalized compiler/runtime mismatch')
 deployment=json.loads((REF/'original-deployment.json').read_text());deployed=bytes.fromhex(deployment['deployed_runtime'].removeprefix('0x'))
 require(len(deployed)==len(raw) and deployment.get('eip170_deployable') is True,'original deployment not the deployable compiler profile')
 copy=bytearray(deployed)
 for span in refs:copy[span['start']:span['start']+32]=bytes(32)
 require(copy==normalized,'original deployment does not match compiler template')
 go='// Code generated by managed-fees-runtime-golden.py; DO NOT EDIT.\npackage evm\n'
 go+='const managedRuntimeBytes = '+str(len(raw))+'\nconst managedRuntimeNormalizedSHA256 = '+json.dumps(meta['normalized_runtime_sha256'])+'\n'
 go+='type managedImmutableRef struct { Name string; Source string; Start int; Length int }\nvar managedImmutableRefs = []managedImmutableRef{\n'
 for span in sorted(refs,key=lambda row:row['start']):go+='{'+json.dumps(span['name'])+','+json.dumps(span['source'])+','+str(span['start'])+','+str(span['length'])+'},\n'
 go+='}\n';path=ROOT/'chain-parser-go/internal/chain/evm/managed_runtime_generated.go';atomic(path,go);subprocess.run(['gofmt','-w',str(path)],check=True)
 fixture={'revision':meta['revision'],'compiler':meta['solc'],'runtime_bytes':len(raw),'normalized_runtime_sha256':meta['normalized_runtime_sha256'],'immutable_refs':refs,'deployed_runtime':deployment['deployed_runtime'],'deployment':{key:deployment[key]for key in ['pool','vault','owner','protocol_collector','pool_id']},'eip170_deployable':True}
 text=json.dumps(fixture,indent=2)+'\n'
 for project in ['integration','chain-parser-go']:atomic(ROOT/project/'test/contracts/managed-fees-runtime.json',text)
 print(json.dumps({'runtime_bytes':len(raw),'immutable_references':len(refs),'eip170_deployable':True}))
if __name__=='__main__':generate()
