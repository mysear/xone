fn token_account(mint: &str, owner: &str, amount: u64, program: &str, rent: &Value) -> Value {
    let mut data = vec![0; 165];
    data[..32].copy_from_slice(&meteora::pubkey(mint).unwrap());
    data[32..64].copy_from_slice(&meteora::pubkey(owner).unwrap());
    data[64..72].copy_from_slice(&amount.to_le_bytes());
    data[108] = 1;
    if program == spl_token_2022::PROGRAM {
        data.extend([2, 2, 0, 8, 0]);
        data.extend(13u64.to_le_bytes());
    }
    json!({"owner":program,"executable":false,"lamports":rent[data.len().to_string()],"data":[STANDARD.encode(data),"base64"]})
}

async fn rpc(State(case): State<Arc<Value>>, Json(call): Json<Value>) -> Json<Value> {
    let params = &call["params"];
    let slot = &case["pool"]["orca_whirlpool"]["bank_slot"];
    let result = match call["method"].as_str().unwrap() {
        "getGenesisHash" => json!(GENESIS),
        "getMultipleAccounts" => {
            let values: Vec<_> = params[0]
                .as_array()
                .unwrap()
                .iter()
                .map(|key| &case["accounts"][key.as_str().unwrap()])
                .collect();
            json!({"context":{"slot":slot},"value":values})
        }
        "getMinimumBalanceForRentExemption" => case["rent"][params[0].to_string()].clone(),
        "getLatestBlockhash" => {
            json!({"context":{"slot":slot},"value":{"blockhash":case["blockhash"],"lastValidBlockHeight":1000}})
        }
        "getFeeForMessage" => json!({"context":{"slot":slot},"value":5000}),
        other => panic!("unexpected RPC method {other}"),
    };
    Json(json!({"jsonrpc":"2.0","id":call["id"],"result":result}))
}

fn run_worker(root: &Path, request: &Value) -> Value {
    let python = std::env::var("XONE_SBF_PYTHON").unwrap_or_else(|_| "python3.11".into());
    let mut child = Command::new(python)
        .args(["-I", "-S", "-B"])
        .arg(root.join("dex-router/crates/simulation/workers/solana_sbf.py"))
        .arg(root.join("integration/artifacts/local/r01-solana-rebuild/python"))
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .unwrap();
    child
        .stdin
        .take()
        .unwrap()
        .write_all(&serde_json::to_vec(request).unwrap())
        .unwrap();
    let output = child.wait_with_output().unwrap();
    serde_json::from_slice(&output.stdout).unwrap()
}

#[tokio::test]
#[ignore = "requires a deployed-program capture generated by orca-token2022-execution-bank.py"]
async fn orca_swap_v2_preparation_and_deployed_program_cpi() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..");
    let bank_path = std::env::var("XONE_ORCA_TOKEN2022_BANK").unwrap();
    let bank: Value = serde_json::from_slice(&std::fs::read(bank_path).unwrap()).unwrap();
    let caller = bank["caller"].as_str().unwrap();
    let recipient = bank["recipient"].as_str().unwrap();
    let ata = |owner: &str, mint: &str, program: &str| {
        meteora::pda(
            &[
                &meteora::pubkey(owner).unwrap(),
                &meteora::pubkey(program).unwrap(),
                &meteora::pubkey(mint).unwrap(),
            ],
            ATA,
        )
        .unwrap()
    };
    for sides in [1u8, 2, 3] {
        for rollover in [false, true] {
            for zero in [true, false] {
                for exact in [true, false] {
                    let mut case = bank.clone();
                    let mut pool: Pool = serde_json::from_value(case["pool"].clone()).unwrap();
                    let state = pool.orca_whirlpool.as_mut().unwrap();
                    state.bank_epoch += u64::from(rollover);
                    if rollover {
                        let empty = state.tick_arrays.last_mut().unwrap();
                        assert!(empty.ticks.is_empty());
                        empty.layout = "sparse".into();
                        case["accounts"][&empty.address] = json!({"owner":SYSTEM,"executable":false,"lamports":890_880,"data":["","base64"]});
                    }
                    let mut clock = STANDARD
                        .decode(case["accounts"][CLOCK]["data"][0].as_str().unwrap())
                        .unwrap();
                    clock[16..24].copy_from_slice(&state.bank_epoch.to_le_bytes());
                    case["accounts"][CLOCK]["data"][0] = STANDARD.encode(clock).into();
                    let tokens = state.token_2022.as_mut().unwrap();
                    if sides & 1 == 0 {
                        tokens.token0 = None;
                    }
                    if sides & 2 == 0 {
                        tokens.token1 = None;
                    }
                    for (mint, vault, asset) in [
                        (&pool.token0, &state.vault0, &tokens.token0),
                        (&pool.token1, &state.vault1, &tokens.token1),
                    ] {
                        if let Some(asset) = asset {
                            for (key, data) in
                                [(mint, &asset.mint_data), (vault, &asset.vault_data)]
                            {
                                let data = hex::decode(data).unwrap();
                                case["accounts"][key] = json!({"owner":spl_token_2022::PROGRAM,"executable":false,"lamports":case["rent"]["182"],"data":[STANDARD.encode(data),"base64"]});
                            }
                        }
                    }
                    let (sell, buy) = if zero {
                        (&pool.token0, &pool.token1)
                    } else {
                        (&pool.token1, &pool.token0)
                    };
                    let side0 = if tokens.token0.is_some() {
                        spl_token_2022::PROGRAM
                    } else {
                        TOKEN
                    };
                    let side1 = if tokens.token1.is_some() {
                        spl_token_2022::PROGRAM
                    } else {
                        TOKEN
                    };
                    let (source_program, dest_program) =
                        if zero { (side0, side1) } else { (side1, side0) };
                    let slot = state.bank_slot;
                    let timestamp_ms = state.bank_unix_timestamp * 1000;
                    let source = ata(caller, sell, source_program);
                    let destination = ata(recipient, buy, dest_program);
                    case["accounts"][&source] =
                        token_account(sell, caller, 100_000, source_program, &case["rent"]);
                    if rollover {
                        case["accounts"][&destination] = json!({"owner":SYSTEM,"executable":false,"lamports":800_000,"data":["","base64"]});
                    } else {
                        case["accounts"][&destination] =
                            token_account(buy, recipient, 155, dest_program, &case["rent"]);
                    }
                    case["pool"] = serde_json::to_value(&pool).unwrap();
                    let amount = if exact { 3000 } else { 5000 };
                    let calculator = if exact {
                        xone_protocol_math::orca::quote_exact_out
                    } else {
                        xone_protocol_math::orca::quote_exact_in
                    };
                    let expected = calculator(&pool, &Amount(amount.into()), zero).unwrap();
                    let expected_input = u64::try_from(&expected.consumed_in.0).unwrap();
                    let expected_output = u64::try_from(&expected.amount_out.0).unwrap();
                    let snapshot: SnapshotRef = serde_json::from_value(json!({
                        "block":{"chain_key":pool.chain_key,"number_or_slot":slot,"hash":case["blockhash"],"parent_hash":case["blockhash"],"timestamp_ms":timestamp_ms},
                        "scope_hash":"0".repeat(64),"adapter_set_hash":"0".repeat(64),"canonical_epoch":1,
                        "journal_seq":1,"schema_version":1,"online_generation":1,"writer_epoch":1,
                        "owner_service":"chain-parser-rust","owner_assignment_version":1
                    })).unwrap();
                    let request = SolanaQuote {
                        context: Context {
                            chain_key: pool.chain_key.clone(),
                            caller: caller.into(),
                            recipient: recipient.into(),
                            sell_token: sell.clone(),
                            buy_token: buy.clone(),
                            slippage_bps: 0,
                            deadline_ms: u64::MAX,
                        },
                        pool: pool.clone(),
                        plan_hash: "0".repeat(64),
                        quote_view_id: "test".into(),
                        snapshot,
                        zero,
                        exact,
                        amount,
                        limit: if exact {
                            expected_input
                        } else {
                            expected_output
                        },
                        expected_input,
                        expected_output,
                    };
                    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
                    let url = format!("http://{}", listener.local_addr().unwrap());
                    let app = Router::new()
                        .route("/", post(rpc))
                        .with_state(Arc::new(case));
                    let server =
                        tokio::spawn(async move { axum::serve(listener, app).await.unwrap() });
                    let config = SolanaRpcConfig {
                        url,
                        genesis_hash: GENESIS.into(),
                    };
                    let options =
                        serde_json::from_value(json!({"createDestinationAta":rollover})).unwrap();
                    let prepared = prepare_solana_captured(&config, &request, options)
                        .await
                        .unwrap();
                    server.abort();
                    assert_eq!(prepared.result["ready"], true, "{}", prepared.result);
                    assert_eq!(prepared.result["sourceTokenProgram"], source_program);
                    assert_eq!(prepared.result["destinationTokenProgram"], dest_program);
                    assert_eq!(prepared.result["accountCreation"], rollover);
                    let captured = prepared.accounts.unwrap();
                    let (accounts, absent): (Vec<_>, Vec<_>) = captured
                        .accounts
                        .into_iter()
                        .partition(|(_, v)| !v.is_null());
                    let mut vm_request = json!({
                        "protocol":"xone-local-sbf/1","caller":caller,"recipient":recipient,"sellToken":sell,"buyToken":buy,"maxComputeUnits":1_400_000,
                        "preparation":prepared.result,"bank":{"pool":pool,"accounts":accounts.into_iter().collect::<serde_json::Map<_,_>>(),"absentAccounts":absent.into_iter().map(|(k,_)|k).collect::<Vec<_>>(),"rpcCapture":true}
                    });
                    let actual = run_worker(&root, &vm_request);
                    assert_eq!(
                        actual["success"], true,
                        "sides={sides} rollover={rollover} zero={zero} exact={exact}: {actual}"
                    );
                    assert_eq!(actual["actualInput"], expected_input.to_string());
                    assert_eq!(actual["actualOutput"], expected_output.to_string());
                    assert_eq!(actual["sourceBankUnchanged"], true);
                    let prep = &mut vm_request["preparation"];
                    let (swap_index, swap) = prep["instructions"]
                        .as_array()
                        .unwrap()
                        .iter()
                        .enumerate()
                        .find(|(_, ix)| ix["programId"] == xone_domain::orca::PROGRAM_ID)
                        .unwrap();
                    let data = STANDARD
                        .decode(swap["dataBase64"].as_str().unwrap())
                        .unwrap();
                    let mut message = STANDARD
                        .decode(prep["messageBase64"].as_str().unwrap())
                        .unwrap();
                    let offset = message.windows(data.len()).position(|v| v == data).unwrap();
                    let fail_limit = if exact {
                        expected_input - 1
                    } else {
                        expected_output + 1
                    };
                    message[offset + 16..offset + 24].copy_from_slice(&fail_limit.to_le_bytes());
                    prep["messageBase64"] = STANDARD.encode(&message).into();
                    prep["unsignedTransaction"] =
                        STANDARD.encode(unsigned_packet(&message).unwrap()).into();
                    let failed = run_worker(&root, &vm_request);
                    assert_eq!(failed["error"], "SBF_TRANSACTION_FAILED", "{failed}");
                    let slippage_error = if exact { 6037 } else { 6036 };
                    assert_eq!(
                        failed["nativeError"],
                        json!({"InstructionError":[swap_index,{"Custom":slippage_error}]}),
                        "{failed}",
                    );
                    assert_eq!(failed["sourceBankUnchanged"], true);
                }
            }
        }
    }
}
